#!/usr/bin/env python3
"""Generate the core's NID->name table for every import of a title's modules."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import orbis_elf as oe

ROOT = Path(__file__).resolve().parents[2]
out = Path(sys.argv[1])
app0 = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "build/ghost/app0"
db = oe.load_name_db(ROOT / "build/nid/known_names.txt", ROOT / "ghostldr/data/extra_names.txt")
needed = {}
files = [app0 / "eboot.bin"] + sorted((app0 / "sce_module").glob("*.prx"))
for f in files:
    img = oe.parse(f)
    for sym, _, _ in img.imports():
        if sym.nid in db:
            needed[sym.nid] = db[sym.nid]
# names the loader itself looks up by NID
for name in ("module_start", "module_stop"):
    needed[oe.compute_nid(name)] = name
entries = sorted(needed.items())
lines = ['/* generated by ghostldr/tools/gen_nids.py */', '#include "ghost.h"',
         'struct nid_ent { char nid[12]; const char *name; };',
         '__attribute__((visibility("hidden"))) const struct nid_ent g_nid_table[] = {']
lines += [f'    {{"{nid}", "{name}"}},' for nid, name in entries]
lines += ['};', f'__attribute__((visibility("hidden"))) const u32 g_nid_count = {len(entries)};', '']
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines))
print(f"{out}: {len(entries)} NIDs from {len(files)} files")
