#!/usr/bin/env python3
"""Pack Luac0re's Lua modules into two files for a small SWRR save.

The save image uses 32 KiB blocks, so sixteen tiny module files cost sixteen
blocks.  bundle.lua registers every module in package.preload; init.lua is
Luac0re's own init with one dofile() added before "require 'main'".

    python3 ghostldr/tools/bundle_luac0re.py build/luac0re-src/lua build/swrr-save/stage2/lua
"""

import sys
from pathlib import Path

src, dst = Path(sys.argv[1]), Path(sys.argv[2])
dst.mkdir(parents=True, exist_ok=True)
modules = sorted(p for p in list(src.glob("*.lua")) + list(src.glob("jit/*.lua")) if p.name != "init.lua")

parts = ["-- generated by ghostldr/tools/bundle_luac0re.py from Luac0re 2.4b (MIT, Gezine)"]
for p in modules:
    body = p.read_text()
    if "]==]" in body:
        raise SystemExit(f"{p} contains the long-bracket terminator")
    parts.append(
        f'package.preload["{p.stem}"] = function(...)\n'
        f'    return assert(load([==[{body}]==], "@{p.relative_to(src)}"))(...)\n'
        f"end"
    )
(dst / "bundle.lua").write_text("\n".join(parts) + "\n")

init = (src / "init.lua").read_text()
anchor = "-- Add sanity check to require"
if init.count(anchor) != 1:
    raise SystemExit("Luac0re init.lua changed; update the bundle anchor")
init = init.replace(anchor, 'dofile("/savedata0/lua/bundle.lua")\n\n' + anchor)
(dst / "init.lua").write_text(init)
print(f"bundled {len(modules)} modules: {(dst / 'bundle.lua').stat().st_size} bytes")
