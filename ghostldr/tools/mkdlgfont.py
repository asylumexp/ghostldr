#!/usr/bin/env python3
"""Write the drawn dialogs' bitmap font (ghostldr/native/ext/src/dlg_font.h).

    python3 ghostldr/tools/mkdlgfont.py [--check]

The extension draws system dialogs over a title's frames (dlg_overlay.c).
It needs text, but its code and read-only data take new JIT memory, of which
a 13.60 PS5 has little to spare, so it carries no outline font and no
rasterizer: this tool rasterizes the game selector's built-in font (Noto
Sans, selector/font/notosans.glf, SIL OFL 1.1) once, with the selector's own
rasterizer (selector/src/font.c, built for this computer), at one size, and
keeps 4-bit coverage of printable ASCII and a few symbols: about 9 KB.

--check: exit 1 when the checked-in header differs from what this writes
(tests/test_dlg_font.py).
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEL = ROOT / "native/selector"
OUT = ROOT / "native/ext/src/dlg_font.h"
PX = 28
EXTRA = [0x2026, 0x2022, 0x2190, 0x2192]  # ellipsis, bullet (passwords), arrows (the keyboard)

GEN_C = r"""
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "sel.h"
void *sel_alloc(struct sel *S, u64 n) { (void)S; return calloc(1, n); }
int font_init(struct sel *S, const u8 *glf, u64 cache_bytes);
const struct glyph *font_glyph(struct sel *S, int px, u32 cp);
int font_ascent(struct sel *S, int px);
int main(int argc, char **argv)
{
    FILE *f = fopen(argv[1], "rb");
    if (!f) return 2;
    static u8 glf[1 << 20];
    size_t n = fread(glf, 1, sizeof(glf), f);
    fclose(f);
    if (!n) return 2;
    static struct sel S;
    int px = atoi(argv[2]);
    if (font_init(&S, glf, 8u << 20)) return 3;
    printf("ascent %d\n", font_ascent(&S, px));
    for (int i = 3; i < argc; i++) {
        u32 cp = (u32)strtoul(argv[i], 0, 0);
        const struct glyph *g = font_glyph(&S, px, cp);
        if (!g) { printf("glyph %u none\n", cp); continue; }
        printf("glyph %u %d %d %d %d %d", cp, g->w, g->h, g->left, g->top, g->adv);
        for (int k = 0; k < g->w * g->h; k++) printf(" %d", g->alpha[k]);
        printf("\n");
    }
    return 0;
}
"""


def rasterize(px: int, cps: list[int]) -> tuple[int, dict[int, tuple]]:
    cc = shutil.which("cc") or shutil.which("clang")
    if not cc:
        raise SystemExit("no C compiler for this computer (cc)")
    with tempfile.TemporaryDirectory() as td:
        gen = Path(td) / "gen.c"
        gen.write_text(GEN_C)
        exe = Path(td) / "gen"
        subprocess.run([cc, "-O1", "-std=gnu11", "-fno-math-errno", f"-I{SEL / 'src'}", str(gen),
                        str(SEL / "src/font.c"), "-o", str(exe), "-lm"], check=True)
        out = subprocess.run([str(exe), str(SEL / "font/notosans.glf"), str(px)] + [str(c) for c in cps],
                             capture_output=True, text=True, check=True).stdout
    ascent, glyphs = 0, {}
    for line in out.splitlines():
        f = line.split()
        if f[0] == "ascent":
            ascent = int(f[1])
        elif f[0] == "glyph" and f[2] != "none":
            cp, w, h, left, top, adv = (int(v) for v in f[1:7])
            glyphs[cp] = (w, h, left, top, adv, [int(v) for v in f[7:]])
    return ascent, glyphs


def trim(w: int, h: int, left: int, top: int, a: list[int]) -> tuple[int, int, int, int, list[int]]:
    """Drop empty rows and columns around the coverage (4-bit: below 8 is empty)."""
    rows = [y for y in range(h) if any(a[y * w + x] >= 8 for x in range(w))]
    cols = [x for x in range(w) if any(a[y * w + x] >= 8 for y in range(h))]
    if not rows or not cols:
        return 0, 0, 0, 0, []
    y0, y1, x0, x1 = rows[0], rows[-1] + 1, cols[0], cols[-1] + 1
    out = [a[y * w + x] for y in range(y0, y1) for x in range(x0, x1)]
    return x1 - x0, y1 - y0, left + x0, top - y0, out


def render() -> str:
    cps = list(range(0x20, 0x7F)) + EXTRA
    ascent, glyphs = rasterize(PX, cps)
    rows, bits = [], bytearray()
    for i, cp in enumerate(cps):
        if cp not in glyphs:
            raise SystemExit(f"U+{cp:04X} is not in notosans.glf")
        w, h, left, top, adv, a = glyphs[cp]
        w, h, left, top, a = trim(w, h, left, top, a)
        nib = [min(15, (v * 15 + 127) // 255) for v in a]
        off = len(bits)
        for k in range(0, len(nib), 2):
            bits.append(nib[k] | (nib[k + 1] << 4 if k + 1 < len(nib) else 0))
        rows.append(f"    {{{w}, {h}, {left}, {top}, {(adv + 32) >> 6}, {off}}}, /* U+{cp:04X} */")
    line_h = round(PX * 1.36)
    body = ",".join(("\n    " if k % 24 == 0 else " ") + f"0x{b:02x}" for k, b in enumerate(bits))
    extra = ", ".join(f"0x{c:04X}" for c in EXTRA)
    return f"""/* Generated by ghostldr/tools/mkdlgfont.py: do not edit.  Noto Sans Regular
 * (SIL Open Font License 1.1, ghostldr/native/selector/font/OFL.txt) at
 * {PX} px, rasterized by the game selector's font.c: printable ASCII, then
 * {extra}.  4-bit coverage, two pixels a byte (low nibble first), row
 * by row from the glyph's top left. */
#define DLGF_PX {PX}
#define DLGF_ASCENT {ascent}
#define DLGF_LINE {line_h}
#define DLGF_FIRST 0x20
#define DLGF_ASCII {0x7F - 0x20}
static const u32 k_dlgf_extra[] = {{{extra}}};
struct dlgf_glyph {{
    u8 w, h;
    s8 left, top; /* from the pen; top: above the baseline */
    u8 adv;
    u16 off;      /* into k_dlgf_bits */
}};
static const struct dlgf_glyph k_dlgf[] = {{
{chr(10).join(rows)}
}};
static const u8 k_dlgf_bits[{len(bits)}] = {{{body}
}};
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        same = OUT.exists() and OUT.read_text() == text
        print(f"{OUT}: {'up to date' if same else 'differs from mkdlgfont.py output'}")
        return 0 if same else 1
    OUT.write_text(text)
    print(f"{OUT}: {len(text)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
